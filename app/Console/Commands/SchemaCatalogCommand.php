<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Database\ConnectionInterface;

/**
 * Generates docs/SCHEMA_CATALOG.md from the LIVE PostgreSQL catalog plus the
 * Generation-1 data contract (config/data_contract.php): ownership, kind,
 * migration class, columns, generated values, constraints, foreign keys
 * (cross-context references), triggers and indexes.
 *
 *   php artisan dgway:schema:catalog            (rewrite the document)
 *   php artisan dgway:schema:catalog --check    (exit 1 if the document is stale; used by the test suite)
 */
final class SchemaCatalogCommand extends Command
{
    protected $signature = 'dgway:schema:catalog {--output=docs/SCHEMA_CATALOG.md} {--check : Fail if the file differs from the live schema}';

    protected $description = 'Generate the schema catalog (ownership, immutability, constraints) from the live database';

    public function handle(ConnectionInterface $db): int
    {
        $markdown = $this->render($db);
        $path = base_path((string) $this->option('output'));

        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $markdown) {
                $this->error("{$path} is stale. Run: php artisan dgway:schema:catalog");

                return self::FAILURE;
            }
            $this->info('Schema catalog is up to date.');

            return self::SUCCESS;
        }

        file_put_contents($path, $markdown);
        $this->info("Written {$path}");

        return self::SUCCESS;
    }

    private function render(ConnectionInterface $db): string
    {
        $contract = config('data_contract.tables');
        ksort($contract);
        $owner = fn (string $t) => $contract[$t]['context'] ?? '?';

        $out = [];
        $out[] = '# Schema catalog — DG Way Core Transactional Data, Generation 1';
        $out[] = '';
        $out[] = '> GENERATED by `php artisan dgway:schema:catalog` from the live PostgreSQL catalog and';
        $out[] = '> `config/data_contract.php`. Do not edit by hand; the test suite fails when it is stale.';
        $out[] = '> Strategy and meaning: docs/DATA_EVOLUTION_STRATEGY.md.';
        $out[] = '';
        $out[] = '## Tables';
        $out[] = '';
        $out[] = '| Table | Owner context | Aggregate | Kind | Migration | Business key |';
        $out[] = '| --- | --- | --- | --- | --- | --- |';
        foreach ($contract as $t => $c) {
            $out[] = "| `{$t}` | {$c['context']} | {$c['aggregate']} | {$c['kind']} | {$c['migration']} | ".($c['business_key'] ?? '—').' |';
        }

        $out[] = '';
        $out[] = '## Cross-context references (foreign keys between different owners)';
        $out[] = '';
        $out[] = '| From | Column | To | Owner → Owner | On delete |';
        $out[] = '| --- | --- | --- | --- | --- |';
        foreach ($this->foreignKeys($db) as $fk) {
            if ($owner($fk->from_table) !== $owner($fk->to_table)) {
                $out[] = "| `{$fk->from_table}` | {$fk->columns} | `{$fk->to_table}` | {$owner($fk->from_table)} → {$owner($fk->to_table)} | {$fk->on_delete} |";
            }
        }

        foreach ($contract as $t => $c) {
            if ($c['kind'] === 'framework') {
                continue;
            }
            $out[] = '';
            $out[] = "## `{$t}`";
            $out[] = '';
            $out[] = "Owner **{$c['context']}** · aggregate {$c['aggregate']} · kind **{$c['kind']}** · migration **{$c['migration']}**";
            $out[] = '';
            $out[] = '| Column | Type | Null | Default / generated |';
            $out[] = '| --- | --- | --- | --- |';
            foreach ($db->select(<<<'SQL'
                SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, NOT a.attnotnull AS nullable,
                       a.attgenerated AS generated, pg_get_expr(d.adbin, d.adrelid) AS expr
                FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                WHERE a.attrelid = ?::regclass AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum
            SQL, [$t]) as $col) {
                $expr = $col->expr === null ? '' : ($col->generated === 's' ? 'GENERATED: '.$col->expr : $col->expr);
                $out[] = "| {$col->name} | {$col->type} | ".($col->nullable ? 'yes' : 'no').' | '.self::cell($expr).' |';
            }
            $constraints = $db->select(<<<'SQL'
                SELECT conname AS name, contype AS type, pg_get_constraintdef(oid) AS def
                FROM pg_constraint WHERE conrelid = ?::regclass ORDER BY contype, conname
            SQL, [$t]);
            if ($constraints !== []) {
                $out[] = '';
                $out[] = 'Constraints:';
                foreach ($constraints as $k) {
                    $label = ['p' => 'PK', 'u' => 'UNIQUE', 'f' => 'FK', 'c' => 'CHECK', 'x' => 'EXCLUDE'][$k->type] ?? $k->type;
                    $out[] = "- {$label} `{$k->name}`: `".self::cell($k->def).'`';
                }
            }
            $triggers = $db->select(<<<'SQL'
                SELECT t.tgname AS name, p.proname AS fn, pg_get_triggerdef(t.oid) AS def
                FROM pg_trigger t JOIN pg_proc p ON p.oid = t.tgfoid WHERE t.tgrelid = ?::regclass AND NOT t.tgisinternal ORDER BY t.tgname
            SQL, [$t]);
            if ($triggers !== []) {
                $out[] = '';
                $out[] = 'Triggers:';
                foreach ($triggers as $tr) {
                    $when = preg_match('/(BEFORE|AFTER) (.+?) ON/', $tr->def, $m) ? "{$m[1]} {$m[2]}" : '';
                    $deferred = str_contains($tr->def, 'DEFERRED') ? ' · DEFERRED (at COMMIT)' : '';
                    $out[] = "- `{$tr->name}` → `{$tr->fn}()` ({$when}{$deferred})";
                }
            }
            $indexes = $db->select("SELECT indexname AS name, indexdef AS def FROM pg_indexes WHERE schemaname = 'public' AND tablename = ? ORDER BY indexname", [$t]);
            if ($indexes !== []) {
                $out[] = '';
                $out[] = 'Indexes:';
                foreach ($indexes as $ix) {
                    $out[] = "- `{$ix->name}`: `".self::cell(preg_replace('/^CREATE (UNIQUE )?INDEX \S+ ON public\.\S+ USING /', '$1', $ix->def)).'`';
                }
            }
        }

        return implode("\n", $out)."\n";
    }

    /** @return list<object> */
    private function foreignKeys(ConnectionInterface $db): array
    {
        return $db->select(<<<'SQL'
            SELECT c.conrelid::regclass::text AS from_table, c.confrelid::regclass::text AS to_table,
                   (SELECT string_agg(a.attname, ', ' ORDER BY a.attnum) FROM pg_attribute a WHERE a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey)) AS columns,
                   CASE c.confdeltype WHEN 'r' THEN 'RESTRICT' WHEN 'a' THEN 'NO ACTION' WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL' ELSE 'SET DEFAULT' END AS on_delete
            FROM pg_constraint c WHERE c.contype = 'f' AND c.connamespace = 'public'::regnamespace
            ORDER BY 1, 3
        SQL);
    }

    private static function cell(string $s): string
    {
        return str_replace(['|', "\n"], ['\|', ' '], preg_replace('/\s+/', ' ', $s));
    }
}
