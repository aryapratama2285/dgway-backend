<?php

declare(strict_types=1);

namespace Tests\Feature\DataEvolution;

use Illuminate\Support\Facades\DB;
use Tests\DatabaseTestCase;

/**
 * The Generation-1 data contract (config/data_contract.php) must describe the
 * real database: no undeclared table, and every declared guarantee present.
 * A new table therefore cannot be added without saying who owns it and how
 * it survives a migration to Project B.
 */
final class DataContractTest extends DatabaseTestCase
{
    private const CONTEXTS = ['Identity', 'Catalog', 'Partner', 'Network', 'Procurement', 'Inventory', 'Sales', 'Payment', 'Shared', 'Framework'];
    private const KINDS = ['master', 'document', 'line', 'append_only', 'projection', 'counter', 'operational', 'framework'];
    private const MIGRATIONS = ['preserve', 'carry_over', 'rebuild', 'discard'];

    /** @return array<string, array<string, mixed>> */
    private function contract(): array
    {
        return config('data_contract.tables');
    }

    /** @return list<string> */
    private function triggerFunctions(string $table): array
    {
        return array_map(fn ($r) => $r->fn, DB::select(<<<'SQL'
            SELECT p.proname AS fn FROM pg_trigger t JOIN pg_proc p ON p.oid = t.tgfoid
            WHERE t.tgrelid = ?::regclass AND NOT t.tgisinternal
        SQL, [$table]));
    }

    public function test_every_table_is_declared_and_every_declaration_exists(): void
    {
        $actual = array_map(fn ($r) => $r->table_name, DB::select("SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE' ORDER BY 1"));
        $declared = array_keys($this->contract());
        sort($declared);
        $this->assertSame($actual, $declared, 'config/data_contract.php must list exactly the tables in the database');
    }

    public function test_declarations_are_well_formed(): void
    {
        foreach ($this->contract() as $table => $c) {
            $this->assertContains($c['context'], self::CONTEXTS, $table);
            $this->assertContains($c['kind'], self::KINDS, $table);
            $this->assertContains($c['migration'], self::MIGRATIONS, $table);
            if ($c['migration'] === 'preserve') {
                $this->assertNotEmpty($c['fingerprint'] ?? [], "{$table}: preserved tables need a semantic fingerprint");
                $this->assertSame('id', $c['fingerprint'][0], "{$table}: fingerprint starts with the stable id");
            }
        }
    }

    public function test_preserved_tables_have_a_client_generated_uuid_primary_key(): void
    {
        foreach ($this->contract() as $table => $c) {
            if ($c['migration'] !== 'preserve') {
                continue;
            }
            $pk = DB::selectOne(<<<'SQL'
                SELECT a.attname AS col, format_type(a.atttypid, a.atttypmod) AS type, pg_get_expr(d.adbin, d.adrelid) AS default
                FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
                LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                WHERE i.indrelid = ?::regclass AND i.indisprimary
            SQL, [$table]);
            $this->assertSame('id', $pk->col, "{$table}: primary key must be id");
            $this->assertSame('uuid', $pk->type, "{$table}: id must be a UUID (portable, not a database sequence)");
            $this->assertNull($pk->default, "{$table}: id is generated by the application (UUIDv7), never by the database");
        }
    }

    public function test_fingerprint_columns_exist(): void
    {
        foreach ($this->contract() as $table => $c) {
            foreach ($c['fingerprint'] ?? [] as $col) {
                $this->assertTrue(DB::table('information_schema.columns')->where('table_schema', 'public')->where('table_name', $table)->where('column_name', $col)->exists(), "{$table}.{$col}");
            }
        }
    }

    public function test_declared_immutability_is_enforced_by_the_database(): void
    {
        foreach ($this->contract() as $table => $c) {
            $fns = $this->triggerFunctions($table);
            match ($c['kind']) {
                'append_only' => $this->assertContains('dgway_forbid_mutation', $fns, "{$table} is declared append-only"),
                'master' => $this->assertContains('dgway_guard_identity', $fns, "{$table} is declared a stable identity"),
                'document' => $this->assertNotEmpty(array_intersect($fns, ['dgway_goods_receipt_guard', 'dgway_sale_guard', 'dgway_forbid_mutation']), "{$table} needs a status/immutability or no-delete guard"),
                default => null,
            };
        }
    }
}
